const mismatches=freeze.files.filter(f=>createHash('sha256').update(execFileSync('git',['show',`${implementation}:${f.path}`]).toString('utf8').replaceAll('\r\n','\n')).digest('hex')!==f.lfSha256).map(f=>f.path);
